// Writes docs/SCHOLAR_REVIEW.md: the short, complete list of what a scholar needs to look at.
// Everything not listed is universal everyday content (water, food, day and night, family, numbers…) and needs no review.
import { writeFileSync } from 'node:fs';
import { loadContentFromDisk } from '../app/src/core/loadDisk';
import { sceneTexts } from '../app/src/core/content';
import { classifyText, classifyScene } from '../app/src/core/review';
import { baseForm } from '../app/src/core/arabic';

export function writeScholarList(root = process.cwd()) {
  const c = loadContentFromDisk(root);
  const phrases = new Map<string, { ar: string; where: Set<string> }>();
  let total = 0, universal = 0;
  for (const s of c.scenes) for (const x of sceneTexts(s)) {
    if (/\.tile\d+$|\.recast$/.test(x.where)) continue;
    total++;
    const cls = classifyText(x.ar);
    if (cls === 'universal') { universal++; continue; }
    const key = baseForm(x.ar);
    const e = phrases.get(key) ?? { ar: x.ar, where: new Set<string>() };
    e.where.add(s.id); phrases.set(key, e);
  }
  const sacredScenes = c.scenes.filter((s) => classifyScene(s) === 'sacred');
  const lines = [
    '# Scholar review list (generated — do not edit by hand)',
    '',
    `Generated by \`tools/scholar-list.ts\`. **${universal} of ${total} texts (${Math.round((universal / total) * 100)}%) are universal everyday content and need no review.** Only the items below need a scholar's eye.`,
    '',
    '## 1. Everyday expressions that mention God, and the masjid as a landmark (cultural)',
    '| Phrase | Used in |', '|---|---|',
    ...[...phrases.values()].sort((a, b) => b.where.size - a.where.size).map((p) => `| ${p.ar} | ${[...p.where].join(', ')} |`),
    '',
    '## 2. Worship and scripture content (sacred, optional only)',
    sacredScenes.length ? sacredScenes.map((s) => `- ${s.id} (${s.optional ? 'optional' : '**NOT optional — must be fixed**'})`).join('\n') : '- None in the current game. The optional Quran track and the optional Madinah chapter will be listed here when they are built.',
    '',
    '## 3. Standing questions',
    '- The game\'s hard rules (no faces, modest dress, all-male cast, no music) and how they are applied.',
    '- Showing Quran text and translation to non-Muslim players in the optional Quran track.',
    '- Character names and the optional Madinah chapter (no depiction of Masjid an-Nabawi, prophets or Companions).',
  ];
  writeFileSync(`${root}/docs/SCHOLAR_REVIEW.md`, lines.join('\n') + '\n');
  return { total, universal, cultural: phrases.size, sacredScenes: sacredScenes.length };
}

if (process.argv[1]?.endsWith('scholar-list.ts')) console.log(writeScholarList());
